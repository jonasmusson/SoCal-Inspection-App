export function getMakesForYear(year: number): string[] {
  return MAKES
    .filter(m => year >= m.years[0] && (m.years[1] === null || year <= m.years[1]))
    .map(m => m.name)
    .sort();
}

export function getModelsForMakeYear(make: string, year: number): string[] {
  const entry = MAKES.find(m => m.name === make);
  if (!entry) return [];
  return entry.models
    .filter(m => year >= m.years[0] && (m.years[1] === null || year <= m.years[1]))
    .map(m => m.name);
}
